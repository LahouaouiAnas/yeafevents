/** Round icon links to the agency's social profiles; renders nothing until one is set. */
export function SocialLinks({ className = "" }: { className?: string }) {
  if (socialLinks.length === 0) return null;

  return (
    <ul className={`flex flex-wrap gap-3 ${className}`}>
      {socialLinks.map(([network, url]) => {
        const icon = icons[network];
        return (
          <li key={network}>
            <a
              href={url}
              target="_blank"
              rel="noopener noreferrer"
              aria-label={labels[network]}
              title={labels[network]}
              className="flex size-10 items-center justify-center rounded-full border border-ivory/20 text-ivory/70 transition-colors duration-300 hover:border-champagne hover:text-champagne"
            >
              {icon ? (
                <svg aria-hidden="true" viewBox="0 0 24 24" className="size-[18px]" fill="currentColor">
                  <path d={icon} />
                </svg>
              ) : (
                <span className="text-[0.6rem] tracking-wider uppercase">{labels[network].slice(0, 2)}</span>
              )}
            </a>
          </li>
        );
      })}
    </ul>
  );
}
